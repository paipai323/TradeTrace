const assert=require('node:assert/strict');
const C=require('../static/terminal-conditions.js');
const values=[10,14,11,16,12,15,13,17,14,18,15,11,13,10];
const bars=values.map((p,i)=>({time:i+1,open:p,close:p,high:p+.2,low:p-.2}));
const structureRow=(rule='BOS_UP',sensitivity=1)=>({rule,mode:'CANDLE',timeframe:'M5',sensitivity,level:0,low:0,high:0});
const run=new C.Structure(1),events=[];
for(const b of bars)events.push(...run.push(b));
assert.deepEqual(events.map(e=>[e.type,e.direction,e.candle.time]),[['BOS',1,8],['BOS',1,10],['MS',-1,12],['BOS',-1,14]]);
assert.equal(events[0].level,15.2);assert.equal(events[0].swing_time,6);assert.equal(events[0].confirmed_time,7);
assert.equal(events[2].level,13.8);assert.equal(events[2].bias_before,1);assert.equal(events[2].bias_after,-1);
const mirrored=bars.map(b=>({time:b.time,open:30-b.open,close:30-b.close,high:30-b.low,low:30-b.high}));
const bear=new C.Structure(1),down=[];for(const b of mirrored)down.push(...bear.push(b));
assert.deepEqual(down.map(e=>[e.type,e.direction]),[['BOS',-1],['BOS',-1],['MS',1],['BOS',1]]);
const confirmation=new C.Structure(2);
for(const [i,p] of [10,11,15,12].entries())confirmation.push({time:i+1,open:p,close:p,high:p+.2,low:p-.2});
assert.equal(confirmation.highs.length,0,'right-side confirmation is required');
confirmation.push({time:5,open:11,close:11,high:11.2,low:10.8});
assert.equal(confirmation.highs[0].time,3);assert.equal(confirmation.highs[0].confirmed,5);
const ties=new C.Structure(1);for(const [i,p] of [10,14,14,11].entries())ties.push({time:i+1,open:p,close:p,high:p+.2,low:p-.2});
assert.equal(ties.highs.length,0,'equal-high plateaus are not strict swings');
const wick=new C.Structure(1);for(const b of bars.slice(0,7))wick.push(b);
assert.deepEqual(wick.push({time:8,open:14,close:14,high:20,low:13.5}),[],'wick-only breakout does not pass');
assert.equal(wick.bias,1);
const protectedSwing=new C.Structure(1);for(const b of bars.slice(0,7))protectedSwing.push(b);
const protectedPrice=protectedSwing.snapshot('MS_DOWN').level;
protectedSwing.push({time:8,open:13.5,close:13.5,high:13.7,low:11.5});
protectedSwing.push({time:9,open:14,close:14,high:14.2,low:13});
assert.equal(protectedSwing.bias,1,'a lower wick is not a market shift');
assert.equal(protectedSwing.snapshot('MS_DOWN').level,protectedPrice,'a wick-made lower low does not move the protected higher low');
const protectedBreak=protectedSwing.push({time:10,open:11.7,close:11.7,high:11.9,low:11.6});
assert.equal(protectedBreak[0].type,'MS');assert.equal(protectedBreak[0].level,protectedPrice);
const duplicate=new C.Structure(1);for(const b of bars.slice(0,8))duplicate.push(b);
assert.deepEqual(duplicate.push(bars[7]),[],'duplicate candles cannot repeat a signal');
assert.deepEqual(duplicate.push({time:9,open:17,close:17,high:17.2,low:16.8}),[],'a broken swing is consumed');
const sequence=new C.Sequence([structureRow()]);
assert.equal(sequence.observe({bid:13,time:100,candles:bars.slice(0,7)}),false);
assert.equal(sequence.observe({bid:17,time:101,candles:bars.slice(0,8)}),true);
assert.equal(sequence.events[0].structure.type,'BOS');assert.equal(sequence.events[0].structure.candle.time,8);
assert.equal(sequence.observe({bid:18,time:102,candles:bars}),false,'finished structure setups never retry');
const historical=new C.Sequence([structureRow()]);
assert.equal(historical.observe({bid:17,time:100,candles:bars.slice(0,8)}),false,'historical break does not satisfy Start');
assert.equal(historical.observe({bid:17,time:101,candles:bars.slice(0,8)}),false);
const warming=new C.Sequence([structureRow('BOS_UP',2)]);
assert.equal(warming.observe({bid:10,time:100,candles:[]}),false);
assert.match(warming.structureState.status,/Not enough completed candles/);
assert.equal(warming.observe({bid:10,time:101,candles:bars.slice(0,1)}),false);
assert.match(warming.structureState.status,/1\/5/);
const missed=new C.Sequence([structureRow()]);missed.observe({bid:13,time:100,candles:bars.slice(0,7)});
assert.equal(missed.observe({bid:18,time:101,candles:bars.slice(0,10)}),false,'missed closes update context but never trigger late entry');
assert.match(missed.structureState.status,/Skipped 3/);
const ordered=new C.Sequence([structureRow(),structureRow('MS_DOWN')]);
ordered.observe({bid:13,time:100,candles:bars.slice(0,7)});ordered.observe({bid:17,time:101,candles:bars.slice(0,8)});
assert.equal(ordered.index,1);ordered.observe({bid:11,time:102,candles:bars.slice(0,12)});
assert.equal(ordered.index,1,'new step establishes its own baseline, not a previous break');
const neutral=new C.Structure(1);for(const [i,p] of [10,13,11,12,11.5,11.8].entries())neutral.push({time:i+1,open:p,close:p,high:p+.2,low:p-.2});
assert.equal(neutral.bias,0);assert.match(neutral.snapshot('BOS_UP').status,/Waiting for clear structure/);
for(const rule of ['BOS_UP','BOS_DOWN','MS_UP','MS_DOWN']){
 assert.equal(C.candleOnly(rule),true);assert.deepEqual(C.fieldErrors(structureRow(rule)),{});
 assert.ok(C.fieldErrors({...structureRow(rule),mode:'LIVE'}).mode);
 for(const sensitivity of [0,11,1.5,NaN])assert.ok(C.fieldErrors(structureRow(rule,sensitivity)).sensitivity);
}
for(const [rule,history,cut,next] of [['BOS_UP',bars,7,8],['BOS_DOWN',mirrored,7,8],['MS_DOWN',bars,11,12],['MS_UP',mirrored,11,12]]){
 const sequence=new C.Sequence([structureRow(rule)]);
 sequence.observe({bid:history[cut-1].close,time:100,candles:history.slice(0,cut)});
 assert.equal(sequence.observe({bid:history[next-1].close,time:101,candles:history.slice(0,next)}),true,rule+' fires only on its new close');
 assert.equal(sequence.events[0].structure.type,rule.startsWith('BOS')?'BOS':'MS');
}
console.log('BOS / MS confirmed swing and ordered sequence tests passed');
